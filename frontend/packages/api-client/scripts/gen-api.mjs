import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const openapiPath = resolve(root, "openapi.json");
const outPath = resolve(root, "src/generated/schema.d.ts");

if (!existsSync(openapiPath)) {
  console.error(
    "Missing openapi.json. Generate from backend: python -c \"... app.openapi() ...\"",
  );
  process.exit(1);
}

execSync(`pnpm exec openapi-typescript "${openapiPath}" -o "${outPath}"`, {
  stdio: "inherit",
  cwd: root,
});

const banner = "/** Generated by openapi-typescript — do not edit. */\n";
const current = readFileSync(outPath, "utf8");
if (!current.startsWith(banner)) {
  writeFileSync(outPath, banner + current);
}

console.log("Wrote", outPath);
